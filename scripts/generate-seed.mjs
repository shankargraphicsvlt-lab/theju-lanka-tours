// Generates supabase/seed.sql from the site's content files, so the database
// seed always matches what the website shows. Contains editorial content and
// pricing settings only: never customer data.
//
// Usage: npm run db:seed:generate
import { writeFile } from "node:fs/promises";
import { register } from "node:module";
import path from "node:path";

// The site's TypeScript uses extensionless relative imports (e.g. pricing.ts → "./site"),
// which Node only resolves with a ".ts" added. Registered before the source files are loaded.
register(
  "data:text/javascript," +
    encodeURIComponent(
      'export async function resolve(s, c, next) { try { return await next(s, c); } catch (e) { if (/^\\.\\.?\\//.test(s) && !/\\.[cm]?[jt]s$/.test(s)) return next(s + ".ts", c); throw e; } }',
    ),
);
const { destinations } = await import("../src/content/destinations.ts");
const { experiences } = await import("../src/content/experiences.ts");
const { tours } = await import("../src/content/tours.ts");
const { pricingConfig } = await import("../src/config/pricing.ts");

const root = path.resolve(import.meta.dirname, "..");

const q = (s) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const textArray = (items) => (items.length ? `array[${items.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const interestArray = (items) => (items.length ? `array[${items.map(q).join(", ")}]::public.interest[]` : "'{}'::public.interest[]");
const jsonb = (value) => `${q(JSON.stringify(value))}::jsonb`;

const lines = [
  "-- GENERATED by scripts/generate-seed.mjs from src/content and src/config/pricing.ts.",
  "-- Do not edit by hand. Editorial content and pricing only; no customer data.",
  "-- Safe to re-run: rows are upserted by slug.",
  "",
  "begin;",
  "",
];

destinations.forEach((d, i) => {
  lines.push(
    `insert into public.destinations (slug, name, region, tagline, summary, description, highlights, best_time, getting_there, interests, hero_image, gallery, latitude, longitude, sort_order, is_published)
values (${q(d.slug)}, ${q(d.name)}, ${q(d.region)}, ${q(d.tagline)}, ${q(d.summary)}, ${textArray(d.description)}, ${jsonb(d.highlights)}, ${q(d.bestTime)}, ${q(d.gettingThere)}, ${interestArray(d.interests)}, ${q(d.heroImage)}, ${textArray(d.gallery)}, ${d.coordinates.lat}, ${d.coordinates.lng}, ${i}, true)
on conflict (slug) do update set name = excluded.name, region = excluded.region, tagline = excluded.tagline, summary = excluded.summary, description = excluded.description, highlights = excluded.highlights, best_time = excluded.best_time, getting_there = excluded.getting_there, interests = excluded.interests, hero_image = excluded.hero_image, gallery = excluded.gallery, latitude = excluded.latitude, longitude = excluded.longitude, sort_order = excluded.sort_order;`,
  );
});
lines.push("");

experiences.forEach((e, i) => {
  lines.push(
    `insert into public.experiences (slug, title, category, summary, description, what_to_expect, good_to_know, duration_label, image, sort_order, is_published)
values (${q(e.slug)}, ${q(e.title)}, ${q(e.category)}, ${q(e.summary)}, ${textArray(e.description)}, ${textArray(e.whatToExpect)}, ${textArray(e.goodToKnow)}, ${q(e.duration)}, ${q(e.image)}, ${i}, true)
on conflict (slug) do update set title = excluded.title, category = excluded.category, summary = excluded.summary, description = excluded.description, what_to_expect = excluded.what_to_expect, good_to_know = excluded.good_to_know, duration_label = excluded.duration_label, image = excluded.image, sort_order = excluded.sort_order;`,
  );
  lines.push(`delete from public.experience_destinations where experience_id = (select id from public.experiences where slug = ${q(e.slug)});`);
  for (const slug of e.destinations) {
    lines.push(
      `insert into public.experience_destinations (experience_id, destination_id) select e.id, d.id from public.experiences e, public.destinations d where e.slug = ${q(e.slug)} and d.slug = ${q(slug)};`,
    );
  }
});
lines.push("");

tours.forEach((t, i) => {
  lines.push(
    `insert into public.tours (slug, title, summary, description, duration_days, style, interests, pickup, included, excluded, image, is_sample, sort_order, is_published)
values (${q(t.slug)}, ${q(t.title)}, ${q(t.summary)}, ${textArray(t.description)}, ${t.durationDays}, ${q(t.style)}, ${interestArray(t.interests)}, ${q(t.pickup)}, ${textArray(t.included)}, ${textArray(t.excluded)}, ${q(t.image)}, ${t.isSample}, ${i}, true)
on conflict (slug) do update set title = excluded.title, summary = excluded.summary, description = excluded.description, duration_days = excluded.duration_days, style = excluded.style, interests = excluded.interests, pickup = excluded.pickup, included = excluded.included, excluded = excluded.excluded, image = excluded.image, is_sample = excluded.is_sample, sort_order = excluded.sort_order;`,
  );
  const tourId = `(select id from public.tours where slug = ${q(t.slug)})`;
  lines.push(`delete from public.tour_destinations where tour_id = ${tourId};`);
  t.destinations.forEach((slug, pos) => {
    lines.push(
      `insert into public.tour_destinations (tour_id, destination_id, position) select t.id, d.id, ${pos} from public.tours t, public.destinations d where t.slug = ${q(t.slug)} and d.slug = ${q(slug)};`,
    );
  });
  lines.push(`delete from public.tour_itinerary_days where tour_id = ${tourId};`);
  for (const day of t.itinerary) {
    lines.push(
      `insert into public.tour_itinerary_days (tour_id, day_number, title, description, overnight) values (${tourId}, ${day.day}, ${q(day.title)}, ${q(day.description)}, ${q(day.overnight)});`,
    );
  }
});
lines.push("");

lines.push(
  `insert into public.pricing_settings (id, currency, daily_rate_cents, discount_percent, basis, group_size)
values (1, ${q(pricingConfig.currency)}, ${pricingConfig.dailyRateCents}, ${pricingConfig.discountPercent}, ${q(pricingConfig.basis)}, ${pricingConfig.groupSize})
on conflict (id) do update set currency = excluded.currency, daily_rate_cents = excluded.daily_rate_cents, discount_percent = excluded.discount_percent, basis = excluded.basis, group_size = excluded.group_size;`,
);
if (pricingConfig.additionalCharges.length > 0) {
  throw new Error("Seeding additional charges is not supported yet; add them through the admin dashboard.");
}

lines.push("", "commit;", "");

const out = path.join(root, "supabase", "seed.sql");
await writeFile(out, lines.join("\n"), "utf8");
console.log(`Wrote ${path.relative(root, out)} (${destinations.length} destinations, ${experiences.length} experiences, ${tours.length} tours)`);
